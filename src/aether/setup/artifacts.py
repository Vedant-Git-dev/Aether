"""Deploy artifacts built from the answers.

The wizard does not call Render or UptimeRobot; it produces the same
non-secret configuration and the same set of environment variables the old
scripts put on a Render service, then prints the handoff. Nothing here
touches the network, so it is fully testable.
"""

from __future__ import annotations

import base64
import secrets as _secrets
from datetime import UTC, datetime

from .plan import SetupPlan

EMBEDDING_MODEL = "gemini-embedding-001"


def generate_key_b64() -> str:
    """32 random bytes, base64. Prefer the package's own generator."""
    try:
        from aether.memory.crypto import generate_key_b64 as package_generator

        return package_generator()
    except Exception:
        return base64.b64encode(_secrets.token_bytes(32)).decode("ascii")


def generate_token() -> str:
    return _secrets.token_urlsafe(48)[:64]


def ensure_core_secrets(secrets: dict[str, str]) -> dict[str, str]:
    """Fill the keys Aether cannot boot without. Never overwrites a value."""
    secrets.setdefault("AETHER_ENCRYPTION_KEY", generate_key_b64())
    secrets.setdefault("AETHER_TOKEN", generate_token())
    secrets.setdefault("TOKEN_ENC_KEY", generate_key_b64())
    secrets.setdefault("TOKEN_ENC_KEY_ID", datetime.now(UTC).strftime("%Y-%m"))
    return secrets


def build_config(plan: SetupPlan) -> str:
    telegram = "true" if "telegram" in plan.channels else "false"
    discord = "true" if "discord" in plan.channels else "false"
    embedding = EMBEDDING_MODEL if plan.semantic_memory else "off"
    return (
        "# Generated by setup. Secrets live in the environment.\n"
        "llm:\n"
        f"  provider: {plan.llm_provider}\n"
        f"  model: {plan.llm_model}\n"
        f"  embedding_model: {embedding}\n"
        "messaging:\n"
        "  telegram:\n"
        f"    enabled: {telegram}\n"
        "  discord:\n"
        f"    enabled: {discord}\n"
        "media:\n"
        f"  image_provider: {plan.image_provider or 'none'}\n"
        "workbench:\n"
        f"  provider: {plan.workbench_provider or 'none'}\n"
        "providers:\n"
        "  enabled: true\n"
    )


def config_b64(plan: SetupPlan) -> str:
    return base64.b64encode(build_config(plan).encode("utf-8")).decode("ascii")


