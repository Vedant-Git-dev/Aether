def build_env(plan: SetupPlan, secrets: dict[str, str]) -> dict[str, str]:
    """The environment variables the service needs, with no empty values."""
    env: dict[str, str] = {}
    for secret_key, env_name in _SECRET_ENV.items():
        value = secrets.get(secret_key, "")
        if value:
            env[env_name] = value
    env["AETHER_CONFIG_B64"] = config_b64(plan)
    env["PYTHON_VERSION"] = "3.12.11"
    env["NODE_VERSION"] = "22.12.0"
    return env


def mask(value: str) -> str:
    if not value:
        return "(empty)"
    if len(value) <= 8:
        return "********"
    return f"{value[:4]}...{value[-4:]}"


def render_yaml(plan: SetupPlan) -> str:
    """A blueprint with the sync:false secrets the dashboard prompts for."""
    disk = ""
    if plan.plan != "free":
        disk = (
            "    disk:\n"
            "      name: workspace\n"
            "      mountPath: /opt/render/project/src/aether-workspace\n"
            "      sizeGB: 1\n"
        )
    build = (
        'if [ -n "$AETHER_CONFIG_B64" ]; then printf %s "$AETHER_CONFIG_B64" | '
        "base64 -d > config.yaml; fi; cd webapp && npm ci && npm run build && cd .. && pip install ."
    )
    keys = [
        "DATABASE_URL",
        "AETHER_ENCRYPTION_KEY",
        "AETHER_TOKEN",
        "AETHER_CONFIG_B64",
        "AETHER_TOKEN_ENCRYPTION_KEY",
        "AETHER_TOKEN_ENCRYPTION_KEY_ID",
    ]
    provider_key = {
        "anthropic": "ANTHROPIC_API_KEY",
        "openai": "OPENAI_API_KEY",
        "gemini": "GEMINI_API_KEY",
        "nvidia": "NVIDIA_API_KEY",
    }.get(plan.llm_provider)
    if provider_key:
        keys.append(provider_key)
    if any("web search" in item.lower() for item in plan.services):
        keys.append("TAVILY_API_KEY")
    if any("voice-note" in item.lower() for item in plan.services):
        keys.append("GROQ_API_KEY")
    if plan.semantic_memory or (
        any("image generation" in item.lower() for item in plan.services)
        and plan.image_provider == "gemini"
    ):
        keys.append("GEMINI_API_KEY")
    lines = [
        "# Generated by setup. No secrets.",
        "services:",
        "  - type: web",
        f"    name: {plan.service_name}",
        "    runtime: python",
        f"    plan: {plan.plan}",
        f"    region: {plan.region}",
        f"    buildCommand: '{build}'",
        "    startCommand: 'aether'",
        "    healthCheckPath: /healthz",
    ]
    if disk:
        lines.append(disk.rstrip("\n"))
    lines.append("    envVars:")
    lines.append("      - key: PYTHON_VERSION\n        value: '3.12.11'")
    lines.append("      - key: NODE_VERSION\n        value: '22.12.0'")
    seen: set[str] = set()
    for key in keys:
        if key in seen or key in {"PYTHON_VERSION", "NODE_VERSION"}:
            continue
        seen.add(key)
        lines.append(f"      - key: {key}\n        sync: false")
    lines.append(
        "      - key: AETHER_PUBLIC_URL\n"
        "        fromService:\n"
        f"          name: {plan.service_name}\n"
        "          type: web\n"
        "          envVarKey: RENDER_EXTERNAL_URL"
    )
    return "\n".join(lines) + "\n"
