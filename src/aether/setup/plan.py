"""The answers model and its on-disk formats.

``answers.toml`` is the canonical scripted format: top-level snake_case keys,
lists for the multi-select questions. The older ``KEY=value`` answers file the
shell scripts used is still accepted, so existing CI files keep working.
"""

from __future__ import annotations

import contextlib
import os
import tomllib
from collections.abc import Mapping
from dataclasses import dataclass, field, fields
from pathlib import Path
from typing import Any

# The canonical answers file keys, in the order they are asked.
_FIELD_TO_ENV = {
    "database_mode": "DATABASE_MODE",
    "llm_provider": "LLM_PROVIDER",
    "llm_model": "LLM_MODEL",
    "semantic_memory": "SEMANTIC_MEMORY",
    "setup_target": "SETUP_TARGET",
    "services": "SERVICES",
    "apps": "APPS",
    "channels": "CHANNELS",
    "plan": "PLAN",
    "service_name": "SERVICE_NAME",
    "region": "REGION",
    "deploy_source": "DEPLOY_SOURCE",
    "repo_url": "REPO_URL",
    "uptime_mode": "UPTIME_MODE",
    "alert_email": "ALERT_EMAIL",
    "local_copy": "LOCAL_COPY",
    "image_provider": "IMAGE_PROVIDER",
    "workbench_provider": "WORKBENCH_PROVIDER",
}
_ENV_TO_FIELD = {v: k for k, v in _FIELD_TO_ENV.items()}

# Secrets may live in an answers file (keep it owner-only) or in the
# environment. They are never written to answers.toml by the wizard.
SECRET_KEYS = (
    "RENDER_API_KEY",
    "DATABASE_URL",
    "AETHER_ENCRYPTION_KEY",
    "AETHER_TOKEN",
    "TOKEN_ENC_KEY",
    "TOKEN_ENC_KEY_ID",
    "ANTHROPIC_KEY",
    "OPENAI_KEY",
    "GEMINI_KEY",
    "NVIDIA_KEY",
    "TAVILY_KEY",
    "GROQ_KEY",
    "MODAL_TOKEN_ID",
    "MODAL_TOKEN_SECRET",
    "VERCEL_TOKEN",
    "GOOGLE_CLIENT_ID",
    "GOOGLE_CLIENT_SECRET",
    "GOOGLE_PICKER_KEY",
    "GOOGLE_PICKER_APP_ID",
    "LINKEDIN_CLIENT_ID",
    "LINKEDIN_CLIENT_SECRET",
    "TELEGRAM_TOKEN",
    "DISCORD_TOKEN",
    "UPTIME_API_KEY",
)


def _as_list(value: Any) -> list[str]:
    if value is None:
        return []
    if isinstance(value, str):
        return [part.strip() for part in value.split(",") if part.strip()]
    if isinstance(value, (list, tuple)):
        return [str(part).strip() for part in value if str(part).strip()]
    return [str(value)]


def _as_bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() in {"1", "true", "yes", "y", "on"}


@dataclass
class SetupPlan:
    """Every non-secret answer the wizard collects."""

    database_mode: str = "neon"
    llm_provider: str = "anthropic"
    llm_model: str = "claude-opus-5"
    semantic_memory: bool = True
    setup_target: str = "local"
    services: list[str] = field(default_factory=list)
    apps: list[str] = field(default_factory=list)
    channels: list[str] = field(default_factory=list)
    plan: str = "free"
    service_name: str = "aether"
    region: str = "oregon"
    deploy_source: str = "public"
    repo_url: str = ""
    uptime_mode: str = "skip"
    alert_email: str = ""
    local_copy: bool = False
    image_provider: str = "none"
    workbench_provider: str = "none"

    def as_dict(self) -> dict[str, Any]:
        return {item.name: getattr(self, item.name) for item in fields(self)}

    def to_toml(self) -> str:
        """Serialize to the small TOML subset answers use (strings/lists/bool)."""
        lines = [
            "# Aether setup answers. Generated by the setup wizard; no secrets here.",
            "",
        ]
        for item in fields(self):
            value = getattr(self, item.name)
            if isinstance(value, list):
                rendered = ", ".join(_toml_string(part) for part in value)
                lines.append(f"{item.name} = [{rendered}]")
            elif isinstance(value, bool):
                lines.append(f"{item.name} = {'true' if value else 'false'}")
            else:
                lines.append(f"{item.name} = {_toml_string(str(value))}")
        return "\n".join(lines) + "\n"

    def to_env(self) -> str:
        """Serialize to the legacy KEY=value answers the deploy engine reads."""
        lines = ["# Aether setup answers (legacy KEY=value form)."]
        for item in fields(self):
            env_key = _FIELD_TO_ENV.get(item.name)
            if env_key is None:
                continue
            value = getattr(self, item.name)
            if isinstance(value, list):
                rendered = ",".join(str(part) for part in value)
            elif isinstance(value, bool):
                rendered = "yes" if value else "no"
            else:
                rendered = str(value)
            lines.append(f"{env_key}={rendered}")
        return "\n".join(lines) + "\n"


def _toml_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def plan_from_mapping(data: Mapping[str, Any]) -> SetupPlan:
    """Build a plan from TOML keys or the legacy UPPER_CASE env names."""
    plan = SetupPlan()
    known = {item.name for item in fields(plan)}
    for key, value in data.items():
        field_name = key if key in known else _ENV_TO_FIELD.get(key.upper())
        if field_name is None or field_name not in known:
            continue
        if field_name in {"services", "apps", "channels"}:
            setattr(plan, field_name, _as_list(value))
        elif field_name in {"local_copy", "semantic_memory"}:
            setattr(plan, field_name, _as_bool(value))
        else:
            setattr(plan, field_name, str(value).strip())
    if not plan.repo_url and plan.deploy_source == "public":
        plan.repo_url = ""
    return plan


def secrets_from_mapping(data: Mapping[str, Any]) -> dict[str, str]:
    return {
        key: str(value)
        for key, value in data.items()
        if key.upper() in SECRET_KEYS and str(value).strip()
    }


def _parse_env(text: str) -> dict[str, str]:
    data: dict[str, str] = {}
    for raw in text.splitlines():
        line = raw.strip().lstrip("\ufeff")
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        data[key.strip()] = value.strip().strip('"').strip("'")
    return data


def load_answers(path: str | Path) -> tuple[SetupPlan, dict[str, str]]:
    """Read answers.toml, or the legacy KEY=value answers file."""
    file = Path(path)
    text = file.read_text(encoding="utf-8-sig")
    try:
        data: Mapping[str, Any] = tomllib.loads(text)
    except tomllib.TOMLDecodeError:
        data = _parse_env(text)
    return plan_from_mapping(data), secrets_from_mapping(data)


def write_answers(path: str | Path, plan: SetupPlan) -> Path:
    """Write answers.toml atomically: a reader never sees a partial file."""
    file = Path(path)
    file.parent.mkdir(parents=True, exist_ok=True)
    tmp = file.with_name(f".{file.name}.tmp")
    tmp.write_text(plan.to_toml(), encoding="utf-8")
    tmp.replace(file)
    return file


def write_env_answers(path: str | Path, plan: SetupPlan) -> Path:
    """Write the legacy KEY=value answers for the deploy engine, atomically."""
    file = Path(path)
    file.parent.mkdir(parents=True, exist_ok=True)
    tmp = file.with_name(f".{file.name}.tmp")
    tmp.write_text(plan.to_env(), encoding="utf-8")
    tmp.replace(file)
    return file


def write_secrets(path: str | Path, secrets: Mapping[str, str]) -> Path:
    """Write the owner-only secrets file atomically (chmod 600 on POSIX)."""
    file = Path(path)
    file.parent.mkdir(parents=True, exist_ok=True)
    tmp = file.with_name(f".{file.name}.tmp")
    body = "\n".join(f"{key}={value}" for key, value in secrets.items() if value)
    tmp.write_text(body + ("\n" if body else ""), encoding="utf-8")
    with contextlib.suppress(OSError):
        os.chmod(tmp, 0o600)
    tmp.replace(file)
    return file
